//
// ============================================================================
//  与 C 板（靶车主体）的无线链路（RailLink）—— TCP 服务端，端口 3333
// ============================================================================
//
//  【链路怎么搭的】
//    ESP32 开热点 TARGET_CAR → C 板上的 ESP-01S 连上热点 → 主动连本机 3333。
//    所以 ESP32 是 TCP 服务端，C 板是客户端。
//
//  【数据格式】ASCII，一行一条，以 '\n' 结尾，只有两个字段：
//    ESP32 → C 板： "FORWARD,2"     方向,挡位
//                   "IDLE,0"        保活（C 板刷新时间戳并停车）
//    C 板不回任何数据（只收不发）。
//
//  【约定】
//    - PID / 斜坡 / 前馈都写死在 C 板固件里，这条链路不下发参数
//    - 网页离线超过 0.8s 就发 IDLE，避免靶车一直执行最后一条指令
//
// ============================================================================

#ifndef ESP_TARGET_ROBOT_RAIL_LINK_H
#define ESP_TARGET_ROBOT_RAIL_LINK_H

#pragma once

#include "esp_err.h"

// 启动 TCP 服务端（端口 3333），等 C 板的 ESP-01S 连上来。
esp_err_t RailLink_Start();

// 靶车那边的 ESP-01S 当前是否连着 TCP 3333。
// 板上指示灯拿它显示"靶车在不在线"。
bool RailLink_IsConnected();

#endif //ESP_TARGET_ROBOT_RAIL_LINK_H
