//
// ============================================================================
//  提示模块 (Buzzer) —— 蜂鸣器 + 板载指示
// ============================================================================
//
//  【它管什么】
//    板子上那颗 4kHz 无源蜂鸣器（BUZZER1），以及"什么时候该响"的判断。
//
//  【硬件接法】（从原理图 ESP32主控V1.2 读出）
//      GPIO9 ──► R9(1kΩ) ──► Q1 基极 (S8050, NPN)
//      Q1 集电极 ──► 蜂鸣器(−)    蜂鸣器(+) ──► 3.3V
//      Q1 发射极 ──► GND
//
//    所以是"高电平导通"。无源蜂鸣器不会自己发声，必须喂 4kHz 方波
//    （4kHz 是它的谐振频率，这个频率下最响）。
//
//  【响的规则】
//    ① 上电后成功连上过（网页在线 或 与 C 板的链路通）→ 记一笔 ever_connected
//    ② 之后连接断了 → "滴滴滴，滴滴滴"，两组、每组三下，组间隔 0.8s
//    ③ 如果上电后一次都没连上过 → 断链也不响（避免一直嘀嘀嘀）
//
//  【为什么单独一个模块】
//    提示音是"外围反馈"，跟电机控制、通信没有耦合。
//    分出来以后：调电机不用管蜂鸣器，改提示音也不用碰控制环。
//
// ============================================================================

#ifndef ESP_HORIZONTAL_CONTROL_BUZZER_H
#define ESP_HORIZONTAL_CONTROL_BUZZER_H

#pragma once

#include "esp_err.h"
#include <cstdint>

// 初始化蜂鸣器 GPIO + LEDC（上电调一次，不启动任务）
esp_err_t Buzzer_Init();

// 启动监测任务：盯着"网页在线 / C 板链路"，掉线时按规则响
void Buzzer_Start();

// 预设音效（非阻塞，交给任务排队播放）
void Buzzer_PlayLocated();        // 回零完成：两短声（嘀-嘀）

#endif //ESP_HORIZONTAL_CONTROL_BUZZER_H
